"""Приглашение партнёров на мастер-класс через бота — команда /mk_invite.

Зачем отдельный модуль: рассылка «одно мероприятие — один заход», и её тексты
меняются от события к событию. Держим их здесь, а не в bot.py, чтобы не смешивать
разовую кампанию с постоянной логикой бота (правило репо №1: тексты в конфиге).

Как работает (2026-08-03, решение Николь):
- получателям уходит ДВА сообщения: первое — агенту, второе — готовый текст для
  ЕГО клиента, который можно переслать целиком, не редактируя;
- в тексте для клиента стоит персональная ссылка агента (?ref=<slug>) — по ней
  заявка закрепится за ним;
- идемпотентность: факт отправки пишется в notification_attempts (kind=MK_KIND),
  повторный запуск того же мероприятия пропускает уже отправленных.
"""
from __future__ import annotations

# Событие. При следующем МК меняются три строки: KIND, DATE_HUMAN и TOPIC.
MK_KIND = "mk0608"                       # ≤16 символов — ограничение колонки kind
DATE_HUMAN = "6 августа, 18:00 по Дубаю"
TOPIC = "отчёт по Corporate Tax и как законно платить меньше налогов"


def agent_text(name: str | None) -> str:
    """Сопроводительное агенту: что за событие и что с этим делать."""
    greeting = f"{name}, привет! 👋" if name else "Привет! 👋"
    return (
        f"{greeting}\n\n"
        f"🎓 <b>{DATE_HUMAN}</b> — бесплатный Zoom с главным бухгалтером ONCOUNT. "
        f"Разберём {TOPIC}.\n\n"
        "Позовите знакомых бизнесменов — поможем им.\n\n"
        "Ниже готовый текст с вашей персональной ссылкой: перешлите его клиенту "
        "как есть. Все, кто зарегистрируется по ней, закрепятся за вами."
    )


def client_text(link: str) -> str:
    """Готовый текст для клиента агента — пересылается целиком, без правок."""
    return (
        f"Приглашаю на бесплатный вебинар ONCOUNT — {DATE_HUMAN}.\n\n"
        f"Тема: {TOPIC}. Ведёт главный бухгалтер ONCOUNT — лицензированной "
        "бухгалтерской компании в ОАЭ.\n\n"
        "Разберут, кто попадает под 0% Corporate Tax, что нужно успеть до подачи "
        "отчёта и на каких ошибках компании теряют деньги.\n\n"
        f"Регистрация: {link}"
    )


def build(partner, base_url: str) -> tuple[str, str]:
    """Пара сообщений (агенту, для клиента) под конкретного партнёра."""
    link = f"{base_url.rstrip('/')}/mk?ref={partner.ref_slug}"
    return agent_text(partner.first_name), client_text(link)
