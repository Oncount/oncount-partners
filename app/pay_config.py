def is_ready(method: dict) -> bool:
    """Способ готов принимать деньги? Готов = заполнены ВСЕ реквизиты (или есть
    ссылка на оплату) И указана цена. Незаполненный способ страница показывает
    как «уточняется» и не даёт по нему платить — чтобы человек не отправил деньги
    по заглушке и чтобы мы не получили заявление об оплате, которой не было."""
    if not price_of(method):
        return False
    if method.get("link"):
        return True
    fields = method.get("fields") or []
    return bool(fields) and all(f.get("value") for f in fields)


def price_of(method: dict) -> str | None:
    """Цена способа: своя валюта, иначе основная цена продукта.

    own_price=True → фолбэка на цену продукта НЕТ. Продукт стоит в долларах, и
    подставить «$375» на вкладку «Рубли» значит показать человеку сумму, которую
    он не сможет перевести. Такой способ без своей цены считается незаполненным.
    """
    own = method.get("price")
    if method.get("own_price"):
        return own
    return own or PRODUCT.get("price")


def method_by_id(method_id: str | None) -> dict | None:
    """Способ по id (только из белого списка) — нужен, чтобы взять снимок цены
    из КОНФИГА, а не из формы: сумму в нашей записи клиент подставлять не должен."""
    if not method_id:
        return None
    for m in METHODS:
        if m["id"] == method_id:
            return m
    return None


